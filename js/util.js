// Small shared helpers.

export const $ = (s, el = document) => el.querySelector(s);
export const $$ = (s, el = document) => [...el.querySelectorAll(s)];

export function esc(s = '') {
  return String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

export function uid() {
  return Date.now().toString(36) + Math.random().toString(36).slice(2, 8);
}

let mdReady = false;
export function md(text) {
  if (!window.marked || !window.DOMPurify) return `<p>${esc(text).replace(/\n/g, '<br>')}</p>`;
  if (!mdReady) {
    DOMPurify.addHook('afterSanitizeAttributes', node => {
      if (node.tagName === 'A') { node.setAttribute('target', '_blank'); node.setAttribute('rel', 'noopener noreferrer'); }
      if (node.tagName === 'IMG') node.setAttribute('loading', 'lazy');
    });
    mdReady = true;
  }
  return DOMPurify.sanitize(marked.parse(text || '', { breaks: true, gfm: true }));
}

export function safeUrl(u) {
  if (!u) return '';
  try {
    const x = new URL(/^[a-z]+:\/\//i.test(u) ? u : 'https://' + u);
    return /^https?:$/.test(x.protocol) ? x.href : '';
  } catch { return ''; }
}

export function hostOf(u) {
  try { return new URL(u).hostname.replace(/^www\./, ''); } catch { return ''; }
}

export function videoEmbed(url) {
  if (!url) return '';
  let m = url.match(/(?:youtube\.com\/(?:watch\?(?:.*&)?v=|shorts\/|embed\/|live\/)|youtu\.be\/)([\w-]{11})/);
  if (m) return `https://www.youtube-nocookie.com/embed/${m[1]}`;
  m = url.match(/vimeo\.com\/(?:video\/)?(\d+)/);
  if (m) return `https://player.vimeo.com/video/${m[1]}`;
  return '';
}

export function fmtDate(iso, long = false) {
  const d = new Date(iso);
  if (isNaN(d)) return '';
  const diff = (Date.now() - d) / 1000;
  if (!long) {
    if (diff < 60) return 'just now';
    if (diff < 3600) return `${Math.floor(diff / 60)}m ago`;
    if (diff < 86400) return `${Math.floor(diff / 3600)}h ago`;
    if (diff < 7 * 86400) return `${Math.floor(diff / 86400)}d ago`;
  }
  const opts = { year: 'numeric', month: 'short', day: 'numeric' };
  if (long) Object.assign(opts, { hour: 'numeric', minute: '2-digit' });
  return d.toLocaleString(undefined, opts);
}

export function parseTags(s) {
  return [...new Set(String(s || '').split(/[,#\n]/).map(t => t.trim().toLowerCase().replace(/\s+/g, '-')).filter(Boolean))].slice(0, 12);
}

export function fmtSize(n) {
  if (!n) return '';
  if (n < 1024 * 1024) return `${Math.round(n / 1024)} KB`;
  return `${(n / 1024 / 1024).toFixed(1)} MB`;
}

// Shrink big photos before upload (max 2400px) to save Drive space and load faster.
export async function shrinkImage(file, max = 2400, quality = 0.85) {
  if (!/^image\/(jpeg|png|webp)$/.test(file.type) || file.size < 500 * 1024) return file;
  let bmp;
  try { bmp = await createImageBitmap(file, { imageOrientation: 'from-image' }); } catch { return file; }
  const scale = Math.min(1, max / Math.max(bmp.width, bmp.height));
  if (scale === 1 && file.size < 2.5 * 1024 * 1024) { bmp.close?.(); return file; }
  const w = Math.round(bmp.width * scale), h = Math.round(bmp.height * scale);
  const canvas = document.createElement('canvas');
  canvas.width = w; canvas.height = h;
  canvas.getContext('2d').drawImage(bmp, 0, 0, w, h);
  bmp.close?.();
  const png = file.type === 'image/png';
  const type = png ? 'image/png' : 'image/jpeg';
  const blob = await new Promise(r => canvas.toBlob(r, type, quality));
  if (!blob || blob.size >= file.size) return file;
  const name = png ? file.name : file.name.replace(/\.(jpe?g|webp)$/i, '') + '.jpg';
  return new File([blob], name, { type });
}

export function toast(msg, { kind = 'info', action, onAction, timeout = 4500 } = {}) {
  const root = document.getElementById('toasts');
  const el = document.createElement('div');
  el.className = `toast toast-${kind}`;
  el.innerHTML = `<span>${esc(msg)}</span>${action ? `<button type="button">${esc(action)}</button>` : ''}`;
  if (action) el.querySelector('button').onclick = () => { el.remove(); onAction?.(); };
  root.appendChild(el);
  requestAnimationFrame(() => el.classList.add('show'));
  if (timeout) setTimeout(() => { el.classList.remove('show'); setTimeout(() => el.remove(), 300); }, timeout);
  return el;
}

